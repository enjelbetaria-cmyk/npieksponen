    function gambarOrbit()
        cla(ax); hold(ax,'on');
        if modeVisual == 1
            axis(ax,'equal'); axis(ax,[-1.05 1.05 -1.05 1.05]); axis(ax,'off');
            title(ax,'Visualisasi Transisi Elektron: Orbit Ilustratif','FontSize',13,'FontWeight','bold');
            theta = linspace(0,2*pi,500); skala = 0.025;
            for k = 1:6
                r = skala*k^2;
                plot(ax,r*cos(theta),r*sin(theta),'--','Color',warnaOrbit(k,:),'LineWidth',1.3);
                text(ax,r*cos(pi/4)*1.04,r*sin(pi/4)*1.04,sprintf('n = %d',k), ...
                    'FontSize',9,'FontWeight','bold','Color',warnaOrbit(k,:));
            end
            plot(ax,0,0,'o','MarkerSize',17,'MarkerFaceColor',[0.88 0.15 0.13], ...
                'MarkerEdgeColor',[0.35 0.05 0.05],'LineWidth',1.2);
            text(ax,0,-0.075,'Inti atom','HorizontalAlignment','center','FontSize',9,'FontWeight','bold');
            if niAktif ~= nfAktif
                a=pi/4; r1=skala*niAktif^2; r2=skala*nfAktif^2;
                x1=r1*cos(a); y1=r1*sin(a); x2=r2*cos(a); y2=r2*sin(a);
                plot(ax,[x1 x2],[y1 y2],'--','Color',[.25 .25 .25],'LineWidth',1.5);
                quiver(ax,x1,y1,x2-x1,y2-y1,0,'Color',[.9 .1 .1],'LineWidth',2.4,'MaxHeadSize',.8);
                plot(ax,x1,y1,'o','MarkerSize',9,'MarkerFaceColor',[.05 .4 .95],'MarkerEdgeColor','k');
                plot(ax,x2,y2,'o','MarkerSize',9,'MarkerFaceColor',[0 .65 .2],'MarkerEdgeColor','k');
                text(ax,x1+.035,y1+.025,sprintf('n_i = %d',niAktif),'Color',[.05 .3 .8],'FontSize',9,'FontWeight','bold');
                text(ax,x2+.035,y2-.05,sprintf('n_f = %d',nfAktif),'Color',[0 .48 .15],'FontSize',9,'FontWeight','bold');
            end
        else
            cla(ax); hold(ax,'on');
            axis(ax,[0 10 -14.5 0.8]); set(ax,'YGrid','on','XTick',[],'FontSize',9,'Box','on');
            ylabel(ax,'Energi elektron (eV)');
            title(ax,'Diagram Tingkat Energi Atom Hidrogen','FontSize',13,'FontWeight','bold');
            for k=1:6
                E=-13.6/k^2;
                plot(ax,[1.2 5.2],[E E],'-','Color',warnaOrbit(k,:),'LineWidth',2.5);
                text(ax,.8,E,sprintf('n = %d',k),'HorizontalAlignment','right','FontSize',9,'FontWeight','bold','Color',warnaOrbit(k,:));
                text(ax,5.35,E,sprintf('%.2f eV',E),'FontSize',8,'VerticalAlignment','middle');
            end
            if niAktif ~= nfAktif
                Ei=-13.6/niAktif^2; Ef=-13.6/nfAktif^2; xx=7.1;
                plot(ax,[xx xx],[Ei Ef],'-','Color',[.9 .1 .1],'LineWidth',2.5);
                if Ef>Ei
                    plot(ax,xx,Ef,'^','MarkerFaceColor',[.9 .1 .1],'MarkerEdgeColor',[.9 .1 .1],'MarkerSize',8); prosesT='Absorpsi';
                else
                    plot(ax,xx,Ef,'v','MarkerFaceColor',[.9 .1 .1],'MarkerEdgeColor',[.9 .1 .1],'MarkerSize',8); prosesT='Emisi';
                end
                text(ax,7.45,(Ei+Ef)/2,sprintf('%s\nn_i=%d ke n_f=%d',prosesT,niAktif,nfAktif), ...
                    'FontSize',9,'FontWeight','bold','Color',[.75 .1 .1]);
            end
            text(ax,1.2,-14.0,'Garis menunjukkan energi pada setiap keadaan elektron.','FontSize',8,'Color',[.25 .25 .25]);
        end
        hold(ax,'off');
    end

    function ubahTampilan(~,~)
