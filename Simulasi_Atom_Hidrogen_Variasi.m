        gambarOrbit();
    end

% =====================================================
% FUNGSI: MENJALANKAN SIMULASI
% =====================================================

    function jalankanSimulasi(~,~)
        ni = get(popupNi,'Value');
        nf = get(popupNf,'Value');

        if ni == nf
            set(hasil,'String',sprintf([ ...
                'Keadaan awal dan akhir tidak boleh sama.\n\n' ...
                'Silakan pilih dua keadaan berbeda.']));
            gambarSpektrum(NaN);
            return;
        end

        % Energi elektron dalam eV
        Ei = -13.6/(ni^2);
        Ef = -13.6/(nf^2);

        % Energi foton
        E_foton = abs(Ef-Ei);

        % Panjang gelombang dan frekuensi
        lambda_nm = hc/E_foton;
        lambda_m = lambda_nm*1e-9;
        frekuensi = c/lambda_m;

        % Jenis transisi
        if ni > nf
            jenis = 'Emisi';
            proses = 'Elektron menuju keadaan lebih rendah.';
        else
            jenis = 'Absorpsi';
            proses = 'Elektron menuju keadaan lebih tinggi.';
        end

        [deret,wilayah] = identifikasiDeret(nf);

        % Perbarui visualisasi berdasarkan keadaan yang dipilih
        niAktif=ni; nfAktif=nf;
        gambarOrbit();

        % Animasi hanya untuk mode orbit ilustratif
        if modeVisual == 1
            hold(ax,'on'); skala=.025; sudut=pi/4;
            rAwal=skala*ni^2; rAkhir=skala*nf^2;
            xAwal=rAwal*cos(sudut); yAwal=rAwal*sin(sudut);
            xAkhir=rAkhir*cos(sudut); yAkhir=rAkhir*sin(sudut);
            elektron=plot(ax,xAwal,yAwal,'o','MarkerSize',12, ...
                'MarkerFaceColor',[.05 .4 .95],'MarkerEdgeColor','k');
            for k=1:60
                t=k/60;
                set(elektron,'XData',xAwal+t*(xAkhir-xAwal), ...
                    'YData',yAwal+t*(yAkhir-yAwal));
                drawnow; pause(.015);
            end
            hold(ax,'off');
        end

        % Menampilkan keterangan hasil
        teks = sprintf([ ...
            'Transisi: n = %d ke n = %d\n' ...
            'Jenis transisi: %s\n\n' ...
            'Energi awal (Ei): %.2f eV\n' ...
            'Energi akhir (Ef): %.2f eV\n' ...
            'Energi foton: %.2f eV\n' ...
            'Panjang gelombang: %.2f nm\n' ...
            'Frekuensi: %.3e Hz\n\n' ...
            'Deret terkait: %s\n' ...
            'Wilayah spektrum: %s\n\n%s'], ...
            ni,nf,jenis,Ei,Ef,E_foton, ...
            lambda_nm,frekuensi,deret,wilayah,proses);

        set(hasil,'String',teks);
        gambarSpektrum(lambda_nm);
    end

% =====================================================
% FUNGSI: IDENTIFIKASI DERET SPEKTRUM
% =====================================================

    function [deret,wilayah] = identifikasiDeret(nf)
        switch nf
            case 1
                deret = 'Lyman';
                wilayah = 'Ultraviolet';

            case 2
                deret = 'Balmer';
                wilayah = 'Tampak / dekat UV';

            case 3
                deret = 'Paschen';
                wilayah = 'Inframerah';

            case 4
                deret = 'Brackett';
                wilayah = 'Inframerah';

            case 5
                deret = 'Pfund';
                wilayah = 'Inframerah';

            otherwise
                deret = 'Deret lanjut';
                wilayah = 'Inframerah jauh';
        end
    end

% =====================================================
% FUNGSI: SPEKTRUM CAHAYA TAMPAK
% =====================================================

    function gambarSpektrum(lambda)
        cla(axSpektrum);
        hold(axSpektrum,'on');

        batas = [380 450 495 570 590 620 750];

        warna = [
            0.45 0.00 0.75
            0.00 0.20 1.00
            0.00 0.75 0.90
            0.20 0.80 0.20
            0.95 0.90 0.00
            1.00 0.45 0.00];

        for j = 1:6
            patch(axSpektrum, ...
                [batas(j) batas(j+1) batas(j+1) batas(j)], ...
                [0 0 1 1],warna(j,:), ...
                'EdgeColor','none');
        end

        xlim(axSpektrum,[380 750]);
        ylim(axSpektrum,[0 1]);

        set(axSpektrum, ...
            'YTick',[], ...
            'FontSize',8, ...
            'Box','on');

        xlabel(axSpektrum,'Panjang gelombang (nm)', ...
            'FontSize',8);

        if isfinite(lambda) && lambda >= 380 && lambda <= 750
            plot(axSpektrum,[lambda lambda],[0 1], ...
                'k-','LineWidth',2);

            text(axSpektrum,lambda,0.72, ...
                sprintf('%.1f nm',lambda), ...
                'FontSize',8, ...
                'Color','k', ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','bottom');

        elseif isfinite(lambda)
            text(axSpektrum,565,0.5, ...
                'Di luar wilayah tampak', ...
                'FontSize',8, ...
                'Color','k', ...
                'HorizontalAlignment','center');
        end

        hold(axSpektrum,'off');
    end

